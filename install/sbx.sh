# shellcheck shell=bash
#
# Docker Sandboxes defaults: write ~/.sbxenv.yaml, which `sbx env run` and
# `sbx env create` merge into every environment started without a path. It
# adds the sbx/git-identity mixin, filled in with the name and emails from
# git/config and git/frz.config, so sandboxes commit with the same identity
# as the host, including the Frithuz email under ~/Developer/frz, and the
# sbx/claude-sandbox mixin, which tells Claude Code the sandbox is
# disposable so it runs destructive commands without stopping to ask.
#
# The file is generated rather than symlinked: it needs absolute paths
# (this repository, and ~/Developer/frz as the sandbox sees it), and only
# literal values work in it. An existing file is left alone; if it differs
# from what this would write, the run says so.
#
# Also adds the frithuz kits to sbx's kit.allowedSources, so sbx will pull
# them. sbx settings need a Docker sign-in, so that step comes near the end
# of the run (with 1Password installed to sign in with) and runs `sbx login`
# first if needed.
#
# Sourced by install-macos.sh; not meant to be run on its own.

SBX="$BREW_PREFIX/bin/sbx"
SBX_ENV_DEFAULTS="$HOME/.sbxenv.yaml"
# Remote kit sources sbx must allow, added to whatever is allowed already.
SBX_KIT_SOURCES=(quay.io/frithuz/claude-kit quay.io/frithuz/codex-kit)
# The agent started by `sbx env run` when the project doesn't name one: the
# frithuz Claude Code workload kit. A v3 workload goes in kits, with agent set
# to its name; naming the image reference as the agent leaves sbx unable to
# derive sandbox names.
SBX_DEFAULT_AGENT="claude-kit"
SBX_DEFAULT_AGENT_KIT="quay.io/frithuz/claude-kit:latest"

# Print the contents of ~/.sbxenv.yaml. Fails if git/config has no identity.
sbx_env_defaults() {
  local name email frz_email
  name="$(git config --file "$DOTFILES/git/config" --get user.name)" || return 1
  email="$(git config --file "$DOTFILES/git/config" --get user.email)" || return 1
  frz_email="$(git config --file "$DOTFILES/git/frz.config" --get user.email)" || frz_email=""

  cat <<EOF
# Generated by ~/.dotfiles/install/sbx.sh. Defaults for \`sbx env run\` and
# \`sbx env create\` without a path; a project's sbxenv.yaml overrides them.
schemaVersion: "1"
agent: $SBX_DEFAULT_AGENT
workspace: \${{ env.projectDir }}
kits:
  - $SBX_DEFAULT_AGENT_KIT
  - source: $DOTFILES/sbx/claude-sandbox
  - source: $DOTFILES/sbx/git-identity
    args:
      name: "$name"
      email: "$email"
      frzDir: "$HOME/Developer/frz"
      frzEmail: "$frz_email"
EOF
}

configure_sbx_defaults() {
  local label="Docker Sandboxes defaults" tilde='~' shown content
  shown="${SBX_ENV_DEFAULTS//"$HOME"/$tilde}"

  log "$label"

  if ! content="$(sbx_env_defaults)"; then
    note "git/config has no user.name or user.email; not writing $shown."
    SKIPPED+=("$label (no identity in git/config)")
    return 0
  fi

  if [[ -L "$SBX_ENV_DEFAULTS" ]] || { [[ -e "$SBX_ENV_DEFAULTS" ]] && [[ ! -f "$SBX_ENV_DEFAULTS" ]]; }; then
    note "$shown is not a regular file; leaving it alone."
    SKIPPED+=("$label ($shown is not a regular file)")
    return 0
  fi

  if [[ -f "$SBX_ENV_DEFAULTS" ]]; then
    if [[ "$(cat "$SBX_ENV_DEFAULTS")" == "$content" ]]; then
      note "$shown is up to date"
      PRESENT+=("$label ($shown)")
    else
      note "$shown exists and differs from what this script writes; leaving it alone."
      note "To regenerate it, move it aside and re-run this script."
      SKIPPED+=("$label ($shown differs)")
    fi
    return 0
  fi

  if ((DRY_RUN)); then
    note "[dry-run] write $shown:"
    printf '%s\n' "$content" | sed 's/^/      /'
  else
    printf '%s\n' "$content" >>"$SBX_ENV_DEFAULTS"
    note "Wrote $shown"
  fi
  DONE+=("$label ($shown)")
}

# The kit.allowedSources value sbx uses now (a JSON array). Fails, printing
# sbx's error, if sbx can't read its settings (as before a Docker sign-in).
sbx_allowed_sources() {
  local out
  out="$("$SBX" --no-input settings get kit.allowedSources --json 2>&1)" || {
    printf '%s\n' "$out" | head -n 1
    return 1
  }
  printf '%s' "$out" | "$JQ" -c '.value'
}

allow_sbx_kit_sources() {
  local label="Docker Sandboxes kit sources" current updated src err added

  log "$label"

  if [[ ! -x "$SBX" ]] || [[ ! -x "$JQ" ]]; then
    if ((DRY_RUN)); then
      note "[dry-run] add to sbx kit.allowedSources: ${SBX_KIT_SOURCES[*]}"
      note "[dry-run] (signing in with \`sbx login\` first if needed)"
      DONE+=("[dry-run] $label")
    else
      note "sbx or jq not found; kit.allowedSources not changed."
      SKIPPED+=("$label (sbx or jq missing)")
    fi
    return 0
  fi

  if ! current="$(sbx_allowed_sources)"; then
    err="$current"
    if ((DRY_RUN)); then
      note "Can't read sbx settings ($err)."
      note "[dry-run] would sign in with \`sbx login\`, then add: ${SBX_KIT_SOURCES[*]}"
      DONE+=("[dry-run] $label")
      return 0
    fi
    if [[ ! -t 0 ]]; then
      note "Can't read sbx settings ($err)."
      note "Run \`sbx login\`, then re-run this script."
      SKIPPED+=("$label (not signed in to Docker)")
      return 0
    fi
    note "sbx settings need a Docker sign-in (1Password is installed by now)."
    if ! "$SBX" login || ! current="$(sbx_allowed_sources)"; then
      note "Still can't read sbx settings; run \`sbx login\`, then re-run this script."
      SKIPPED+=("$label (not signed in to Docker)")
      return 0
    fi
  fi

  updated="$current"
  added=()
  for src in "${SBX_KIT_SOURCES[@]}"; do
    if printf '%s' "$updated" | "$JQ" -e --arg s "$src" 'index($s) != null' >/dev/null; then
      note "$src is already allowed"
      PRESENT+=("$label ($src)")
    else
      updated="$(printf '%s' "$updated" | "$JQ" -c --arg s "$src" '. + [$s]')"
      added+=("$src")
    fi
  done
  ((${#added[@]})) || return 0

  if ((DRY_RUN)); then
    note "[dry-run] sbx settings set kit.allowedSources '$updated'"
  elif "$SBX" --no-input settings set kit.allowedSources "$updated" >/dev/null; then
    note "kit.allowedSources is now $updated"
  else
    note "sbx rejected the change; kit.allowedSources not changed."
    SKIPPED+=("$label (sbx settings set failed)")
    return 0
  fi
  for src in "${added[@]}"; do
    DONE+=("$label ($src)")
  done
}
